using Npgsql;

namespace ClimaPulse.Repositories;

/// <summary>
/// Shared PostgreSQL plumbing for the repositories. Each call opens its own short-lived
/// connection, so repositories hold no open handles. Constraint violations from the
/// schema (UNIQUE, CHECK, FOREIGN KEY) surface as PostgresException.
/// </summary>
public abstract class PostgresRepositoryBase
{
    private readonly string _connectionString;

    protected PostgresRepositoryBase(string connectionString)
    {
        _connectionString = connectionString;
    }

    /// <summary>Opens a connection. PostgreSQL enforces foreign keys by default.</summary>
    protected NpgsqlConnection OpenConnection()
    {
        var connection = new NpgsqlConnection(_connectionString);
        connection.Open();
        return connection;
    }

    /// <summary>Binds a parameter, turning null into SQL NULL.</summary>
    protected static void AddParam(NpgsqlCommand command, string name, object? value) =>
        command.Parameters.AddWithValue(name, value ?? DBNull.Value);

    /// <summary>Runs an INSERT, UPDATE or DELETE and returns the number of rows changed.</summary>
    protected int ExecuteNonQuery(string sql, Action<NpgsqlCommand> bind)
    {
        using var connection = OpenConnection();
        using var command = connection.CreateCommand();
        command.CommandText = sql;
        bind(command);
        return command.ExecuteNonQuery();
    }

    /// <summary>Runs an INSERT and returns the id PostgreSQL generated for the new row.</summary>
    protected int InsertAndGetId(string sql, Action<NpgsqlCommand> bind)
    {
        using var connection = OpenConnection();

        using (var insert = connection.CreateCommand())
        {
            insert.CommandText = sql;
            bind(insert);
            insert.ExecuteNonQuery();
        }

        // lastval() is per session, and this is the same connection, so it returns the
        // identity value generated by the INSERT just above.
        using var lastId = connection.CreateCommand();
        lastId.CommandText = "SELECT lastval();";
        return Convert.ToInt32(lastId.ExecuteScalar());
    }

    /// <summary>Runs a SELECT and maps every row with the given function.</summary>
    protected List<T> ReadList<T>(
        string sql, Func<NpgsqlDataReader, T> map, Action<NpgsqlCommand>? bind = null)
    {
        using var connection = OpenConnection();
        using var command = connection.CreateCommand();
        command.CommandText = sql;
        bind?.Invoke(command);

        using var reader = command.ExecuteReader();
        var rows = new List<T>();
        while (reader.Read())
            rows.Add(map(reader));
        return rows;
    }

    // ---- reader helpers for nullable columns -----------------------------

    protected static string? NullableString(NpgsqlDataReader r, int i) =>
        r.IsDBNull(i) ? null : r.GetString(i);

    protected static double? NullableDouble(NpgsqlDataReader r, int i) =>
        r.IsDBNull(i) ? null : r.GetDouble(i);

    protected static int? NullableInt(NpgsqlDataReader r, int i) =>
        r.IsDBNull(i) ? null : r.GetInt32(i);

    protected static DateTime Timestamp(NpgsqlDataReader r, int i) =>
        r.GetString(i).ToDateTime();

    protected static DateTime? NullableTimestamp(NpgsqlDataReader r, int i) =>
        r.IsDBNull(i) ? null : r.GetString(i).ToDateTime();
}
